"""Docs that describe data must match the data: the attribute table in CONFIGURATION.md, lens keys, overrides.

To regenerate the attribute table after changing a bundled market:  python tests/test_docs.py
"""
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SKILL = REPO / "skills" / "persona-panel"
CONFIG_DOC = REPO / "docs" / "CONFIGURATION.md"
BEGIN, END = "<!-- attribute-table:begin (generated by tests/test_docs.py) -->", "<!-- attribute-table:end -->"


def attribute_table():
    lines = []
    for name in ("india", "global"):
        market = json.loads((SKILL / "data" / "markets" / f"{name}.json").read_text(encoding="utf-8"))
        lines += [f"**{name}**", "", "| Attribute | Values (default weight) |", "|---|---|"]
        for attr in market["attributes"]:
            values = ", ".join(f"`{v}` {w:g}" for v, w in attr["values"].items())
            lines.append(f"| `{attr['key']}` | {values} |")
        lines.append("")
    return "\n".join(lines).strip()


def doc_table():
    text = CONFIG_DOC.read_text(encoding="utf-8")
    assert BEGIN in text and END in text, "CONFIGURATION.md lost its attribute table markers"
    return text.split(BEGIN, 1)[1].split(END, 1)[0].strip()


def test_attribute_table_matches_the_bundled_markets():
    assert doc_table() == attribute_table(), "run: python tests/test_docs.py, and paste the output into CONFIGURATION.md"


def test_lens_json_keys_are_documented_and_complete():
    doc = CONFIG_DOC.read_text(encoding="utf-8")
    for f in (SKILL / "references" / "lenses").glob("*.json"):
        lens = json.loads(f.read_text(encoding="utf-8"))
        assert lens["name"] == f.stem
        assert len(lens["outcomes"]) == 3, "aggregate.py and report.py use exactly three outcomes"
        assert set(lens["outcome_labels"]) == set(lens["outcomes"])
        assert set(lens["score_labels"]) == set(lens["scores"])
        assert (f.parent / f"{f.stem}.md").exists()
        assert "## Output schema" in (f.parent / f"{f.stem}.md").read_text(encoding="utf-8")
        for key in lens:
            assert f"`{key}`" in doc, f"lens key {key} is not explained in CONFIGURATION.md"


def test_full_review_aliases_documented():
    import paths
    doc = CONFIG_DOC.read_text(encoding="utf-8")
    for alias in sorted(paths.FULL_REVIEW_ALIASES - {""}):
        assert f'`"{alias}"`' in doc or f"`{alias}`" in doc, alias


def test_overrides_doc_matches_sample_personas(home, run_script, tmp_path):
    from conftest import write_json
    ov = write_json(tmp_path / "ov.json", {"multiply": {"not_an_attribute": {"x": 2}}})
    r = run_script("sample_personas.py", "--run", tmp_path / "r", "--mode", "concept", "--n", 30,
                   "--overrides", ov, check=False)
    assert r.returncode != 0 and "unknown attribute 'not_an_attribute'" in r.stderr
    assert "Traceback" not in r.stderr


